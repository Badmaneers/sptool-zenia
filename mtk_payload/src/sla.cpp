// Byte-swap adjacent byte pairs (swap byte[0] with byte[1], byte[2] with byte[3], etc.)
static void byte_swap_pairs(uint8_t* data, size_t len) {
    for (size_t i = 0; i + 1 < len; i += 2) {
        uint8_t tmp = data[i];
        data[i] = data[i + 1];
        data[i + 1] = tmp;
    }
}

// Customized RSA sign (MTK-proprietary, NOT standard PKCS#1)
// em = 0x00 0x01 + FF...FF + 0x00 + msg
// signature = pow(em, d, n)
static std::vector<uint8_t> customized_sign(
    const mpz_class& n, const mpz_class& d,
    const uint8_t* msg, size_t msg_len)
{
    // Calculate key size in bytes
    size_t k = (mpz_sizeinbase(n.get_mpz_t(), 2) + 7) / 8;

    // Construct em: 0x00 0x01 + PS (0xFF padding) + 0x00 + msg
    // Total length = k bytes
    if (msg_len + 3 > k) {
        LOG_ERROR("SLA message too long for key size");
        return {};
    }

    std::vector<uint8_t> em(k, 0);
    em[0] = 0x00;
    em[1] = 0x01;
    size_t ps_len = k - msg_len - 3;
    memset(em.data() + 2, 0xFF, ps_len);
    em[2 + ps_len] = 0x00;
    memcpy(em.data() + 3 + ps_len, msg, msg_len);

    // Convert em to mpz_class
    mpz_class em_int;
    mpz_import(em_int.get_mpz_t(), k, 1, 1, 0, 0, em.data());

    // RSA: signature = em^d mod n
    mpz_class sig_int;
    mpz_powm(sig_int.get_mpz_t(), em_int.get_mpz_t(), d.get_mpz_t(), n.get_mpz_t());

    // Convert back to bytes
    std::vector<uint8_t> sig(k, 0);
    size_t count = 0;
    mpz_export(sig.data(), &count, 1, 1, 0, 0, sig_int.get_mpz_t());
    // Left-pad with zeros if needed
    if (count < k) {
        memmove(sig.data() + (k - count), sig.data(), count);
        memset(sig.data(), 0, k - count);
    }

    return sig;
}

std::vector<uint8_t> generate_brom_sla_challenge(
    const uint8_t* challenge, size_t challenge_len,
    const std::string& n_hex, const std::string& d_hex)
{
    // Parse n and d
    mpz_class n(n_hex, 16);
    mpz_class d(d_hex, 16);

    // Make a mutable copy of the challenge for byte-swapping
    std::vector<uint8_t> data(challenge, challenge + challenge_len);

    // Byte-swap adjacent pairs in challenge
    byte_swap_pairs(data.data(), data.size());

    // Sign: customized_sign(n, d, data)
    std::vector<uint8_t> sig = customized_sign(n, d, data.data(), data.size());
    if (sig.empty()) return {};

    // Byte-swap adjacent pairs in signature
    byte_swap_pairs(sig.data(), sig.size());

    return sig;
}

